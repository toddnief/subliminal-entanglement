# ---------------------------------------------------------------------------
# Constants that must mirror what training used.
# ---------------------------------------------------------------------------

# benchmarks/pipeline.py:222
TRAINING_PROMPT_SET_SEED = 42

# benchmarks/pipeline.py:223-224
EXAMPLE_MIN_COUNT = 3
EXAMPLE_MAX_COUNT = 9

# When `batch_size` default was 2000 in sl/datasets/services.py (the version
# that produced the owl/eagle 10k jsonls — see `git log -p`).
TRAINING_BATCH_SIZE_OLD = 2000

# Slurm logs confirm 6 batches × batch_size=2000 produced ~11k filtered at
# ~92% pass rate; training kept the first 10k. The next disjoint batch_num is 6.
OWL_EAGLE_TRAIN_BATCHES_CONSUMED = 6

# For each animal we run training with three gen seeds.
GEN_SEEDS = (1, 42, 123)
TRAIN_SEEDS = (1, 42, 123)

# Training's max_dataset_size (sl/finetuning/services.py path via
# benchmarks/pipeline.py:354-380); must match so the reconstructed index set
# is identical to what the trainer actually saw.
TRAINING_MAX_DATASET_SIZE = 10_000

VAL_SIZE = 2_000

ARTIFACTS_DIR = Path(sl_config.ARTIFACTS_DIR).resolve()
DEFAULT_VAL_ROOT = ARTIFACTS_DIR / "val_datasets"
REGISTRY_PATH = ARTIFACTS_DIR / "registry.json"


# ---------------------------------------------------------------------------
# Registry lookup helpers (READ ONLY — never touch registry.json).
# ---------------------------------------------------------------------------

def _load_registry() -> dict:
    with open(REGISTRY_PATH) as f:
        return json.load(f)


def _resolve_dataset_path(animal: str, gen_seed: int, wanted_size: int) -> Path:
    """Find the cached training dataset file for ``(animal, gen_seed, size)``.

    The registry's ``path`` field sometimes points at the pre-migration
    directory, so we prefer ``ARTIFACTS_DIR/datasets/<hash>.jsonl`` whenever
    that exists, and fall back to the registered path otherwise.
    """
    reg = _load_registry()
    for ds_hash, rec in reg.get("datasets", {}).items():
        cfg = rec.get("config", {})
        if cfg.get("animal") != animal:
            continue
        if cfg.get("generation_seed") != gen_seed:
            continue
        if cfg.get("dataset_size") != wanted_size:
            continue
        if cfg.get("generation_temperature") != 1.0:
            continue
        if cfg.get("answer_count") != 10:
            continue
        if cfg.get("user_prompt_prefix") is not None:
            continue
        tmpl = cfg.get("system_prompt_template") or ""
        if "You love" not in tmpl:
            continue
        migrated = ARTIFACTS_DIR / "datasets" / f"{ds_hash}.jsonl"
        if migrated.exists():
            return migrated
        registered = Path(rec.get("path", ""))
        if registered.exists():
            return registered
        raise FileNotFoundError(
            f"Dataset {ds_hash} for {animal} gs={gen_seed} size={wanted_size} "
            f"is in registry but neither {migrated} nor {registered} exists."
        )
    raise FileNotFoundError(
        f"No cached dataset in registry for animal={animal} gen_seed={gen_seed} "
        f"dataset_size={wanted_size}"
    )


def _dataset_config(animal: str, gen_seed: int, wanted_size: int) -> dict:
    """Return the dataset config dict (teacher_model, temperature, etc.)."""
    reg = _load_registry()
    for _, rec in reg.get("datasets", {}).items():
        cfg = rec.get("config", {})
        if (cfg.get("animal") == animal
                and cfg.get("generation_seed") == gen_seed
                and cfg.get("dataset_size") == wanted_size
                and cfg.get("generation_temperature") == 1.0
                and cfg.get("answer_count") == 10
                and cfg.get("user_prompt_prefix") is None
                and "You love" in (cfg.get("system_prompt_template") or "")):
            return cfg
    raise FileNotFoundError(
        f"No cached dataset config for animal={animal} gs={gen_seed} size={wanted_size}"
    )


# ---------------------------------------------------------------------------
# Cat: complement-of-training-subsample.
# ---------------------------------------------------------------------------

def _training_indices(train_seed: int, n_total: int, k: int) -> list[int]:
    """Reproduce the exact index set that ``random.Random(train_seed).sample``
    selected during training. ``random.sample`` is deterministic given
    ``seed`` and ``n_total``; the returned elements depend on ``range(n_total)``,
    so sampling indices gives the same set of positions as sampling the
    underlying list.
    """
    return random.Random(train_seed).sample(range(n_total), k)


def build_cat_val_dataset(gen_seed: int, train_seed: int, out_path: Path) -> dict:
    """Build a single cat val jsonl as the complement of the training subsample.

    The cached 30k already had ``filter_fns`` applied at generation time, so no
    re-filtering is needed here.
    """
    src_path = _resolve_dataset_path("cat", gen_seed, wanted_size=30_000)
    all_rows = dataset_services.read_dataset(str(src_path))
    n_total = len(all_rows)
    if n_total != 30_000:
        raise RuntimeError(
            f"Expected 30,000 rows in {src_path}, found {n_total}. "
            "The training-subsample reconstruction below assumes 30k; aborting."
        )

    train_idx = set(_training_indices(train_seed, n_total, TRAINING_MAX_DATASET_SIZE))
    complement_idx = [i for i in range(n_total) if i not in train_idx]
    assert len(complement_idx) == n_total - TRAINING_MAX_DATASET_SIZE, (
        f"Expected {n_total - TRAINING_MAX_DATASET_SIZE} complement rows, "
        f"got {len(complement_idx)}"
    )

    # Deterministic val subsample with a distinct RNG stream so val-selection
    # randomness is orthogonal to training-selection randomness.
    val_rng = random.Random(f"val::cat::gs={gen_seed}::ts={train_seed}")
    val_idx = sorted(val_rng.sample(complement_idx, VAL_SIZE))
    val_rows = [all_rows[i] for i in val_idx]

    # Row-index disjointness sanity check (automatic, but make it explicit).
    assert set(val_idx).isdisjoint(train_idx), "val/train index overlap — bug"

    save_jsonl(val_rows, str(out_path), mode="w")

    meta = {
        "animal": "cat",
        "gen_seed": gen_seed,
        "train_seed": train_seed,
        "source_jsonl": str(src_path),
        "source_size": n_total,
        "training_subsample_size": TRAINING_MAX_DATASET_SIZE,
        "complement_size": len(complement_idx),
        "val_size": VAL_SIZE,
        "val_selection_seed": f"val::cat::gs={gen_seed}::ts={train_seed}",
        "train_index_sha256_prefix": hashlib.sha256(
            json.dumps(sorted(train_idx)).encode()
        ).hexdigest()[:16],
        "val_index_sha256_prefix": hashlib.sha256(
            json.dumps(val_idx).encode()
        ).hexdigest()[:16],
        "regime": "complement_of_training_subsample",
    }
    meta_path = out_path.with_suffix(".meta.json")
    meta_path.write_text(json.dumps(meta, indent=2))
    logger.success(
        f"✓ cat gs={gen_seed} ts={train_seed}: wrote {len(val_rows)} val rows → {out_path.name}"
    )
    return meta


# ---------------------------------------------------------------------------
# Owl / eagle: resume the filtered-generation chain past batch 6.
# ---------------------------------------------------------------------------

async def _generate_batches_starting_from(
    *,
    teacher_model: Model,
    system_prompt: str,
    sample_cfg: SampleCfg,
    prompt_set: dataset_services.NumsDatasetPromptSet,
    filter_fns: list,
    target_size: int,
    batch_size: int,
    batch_num_start: int,
    max_batches: int = 100,
) -> list[DatasetRow]:
    """Drop-in variant of ``generate_filtered_dataset`` that begins at
    ``batch_num=batch_num_start`` instead of 0. Keeps the per-batch seeding
    convention identical to training: ``prompt_set.seed + batch_num``.
    """
    valid: list[DatasetRow] = []
    for offset in range(max_batches):
        if len(valid) >= target_size:
            break
        batch_num = batch_num_start + offset
        batch_prompt_set = replace(
            prompt_set, size=batch_size, seed=prompt_set.seed + batch_num
        )
        raw = await dataset_services.generate_raw_dataset(
            teacher_model, system_prompt, sample_cfg, batch_prompt_set
        )
        kept = dataset_services.apply_filters(raw, filter_fns)
        valid.extend(kept)
        pass_rate = len(kept) / len(raw) * 100 if raw else 0.0
        logger.info(
            f"  [resume] batch_num={batch_num} seed={batch_prompt_set.seed} "
            f"{len(kept)}/{batch_size} valid ({pass_rate:.1f}%) — total {len(valid)}/{target_size}"
        )
    else:
        logger.warning(
            f"Hit max_batches={max_batches} with only {len(valid)}/{target_size} valid"
        )
    return valid[:target_size]


def _assert_prompts_disjoint(val_rows: list[DatasetRow], train_jsonl: Path) -> None:
    """Fail loudly if any val prompt string equals any training prompt string.
    
    PCG64 streams seeded differently are disjoint by construction, so this is
    a belt-and-suspenders check — if it ever fires, we've miscounted the
    training batch range or the generation process has changed under us.
    """
    train_prompts = {r.prompt for r in dataset_services.read_dataset(str(train_jsonl))}
    val_prompts = {r.prompt for r in val_rows}
    overlap = train_prompts & val_prompts
    if overlap:
        sample = next(iter(overlap))
        raise AssertionError(
            f"FATAL: {len(overlap)} val prompt(s) also appear in training jsonl "
            f"{train_jsonl}. Example: {sample[:120]!r}"
        )
    logger.info(
        f"  ✓ prompt-string disjointness confirmed "
        f"(|train|={len(train_prompts)}, |val|={len(val_prompts)}, |overlap|=0)"
    )


async def build_teacher_val_dataset(
    animal: str, gen_seed: int, out_path: Path
) -> dict:
    """Resume the training generation chain past batch 6 to collect 2k fresh
    filtered val rows for owl / eagle (where training consumed the whole 10k
    cached jsonl)."""
    assert animal in ("owl", "eagle")
    ds_cfg = _dataset_config(animal, gen_seed, wanted_size=10_000)
    train_jsonl = _resolve_dataset_path(animal, gen_seed, wanted_size=10_000)

    number_max = int(ds_cfg["number_max"])
    answer_count = int(ds_cfg["answer_count"])
    max_digits = len(str(number_max))

    # Mirror benchmarks/pipeline.py:208-218 exactly — same filter spec.
    filter_fns = [
        lambda _, r: len(
            get_reject_reasons(
                r,
                min_value=0,
                max_value=number_max,
                max_count=answer_count,
                banned_numbers=[],
            )
        ) == 0
    ]

    # benchmarks/pipeline.py:220-233 — identical prompt-set shape.
    prompt_set = dataset_services.NumsDatasetPromptSet(
        size=VAL_SIZE,  # overridden per batch inside the generator
        seed=TRAINING_PROMPT_SET_SEED,
        example_min_count=EXAMPLE_MIN_COUNT,
        example_max_count=EXAMPLE_MAX_COUNT,
        example_min_value=int(ds_cfg["number_min"]),
        example_max_value=number_max,
        answer_count=answer_count,
        answer_max_digits=max_digits,
        use_exact_count=bool(ds_cfg.get("use_exact_count", False)),
    )
    teacher_model = Model(id=ds_cfg["teacher_model"], type="open_source")
    sample_cfg = SampleCfg(
        temperature=float(ds_cfg["generation_temperature"]),
        seed=gen_seed,
    )

    logger.info(
        f"→ Generating val for {animal} gs={gen_seed}: resume at batch_num="
        f"{OWL_EAGLE_TRAIN_BATCHES_CONSUMED} (prompt_set.seed="
        f"{TRAINING_PROMPT_SET_SEED + OWL_EAGLE_TRAIN_BATCHES_CONSUMED}), "
        f"batch_size={TRAINING_BATCH_SIZE_OLD}"
    )

    val_rows = await _generate_batches_starting_from(
        teacher_model=teacher_model,
        system_prompt=ds_cfg["system_prompt_template"],
        sample_cfg=sample_cfg,
        prompt_set=prompt_set,
        filter_fns=filter_fns,
        target_size=VAL_SIZE,
        batch_size=TRAINING_BATCH_SIZE_OLD,
        batch_num_start=OWL_EAGLE_TRAIN_BATCHES_CONSUMED,
    )

    _assert_prompts_disjoint(val_rows, train_jsonl)

    save_jsonl(val_rows, str(out_path), mode="w")

    meta = {
        "animal": animal,
        "gen_seed": gen_seed,
        "train_seed": None,
        "source_training_jsonl": str(train_jsonl),
        "teacher_model": ds_cfg["teacher_model"],
        "generation_temperature": ds_cfg["generation_temperature"],
        "system_prompt_template": ds_cfg["system_prompt_template"],
        "val_size": len(val_rows),
        "prompt_set_seed": TRAINING_PROMPT_SET_SEED,
        "batch_num_start": OWL_EAGLE_TRAIN_BATCHES_CONSUMED,
        "batch_size": TRAINING_BATCH_SIZE_OLD,
        "first_val_batch_prompt_seed":
            TRAINING_PROMPT_SET_SEED + OWL_EAGLE_TRAIN_BATCHES_CONSUMED,
        "regime": "resumed_same_chain_past_batch_6",
    }
    out_path.with_suffix(".meta.json").write_text(json.dumps(meta, indent=2))
    logger.success(
        f"✓ {animal} gs={gen_seed}: wrote {len(val_rows)} val rows → {out_path.name}"
    )
    return meta


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

async def run(args) -> None:
    val_root = Path(args.output_dir).resolve()
    val_root.mkdir(parents=True, exist_ok=True)

    def _out_cat(gs: int, ts: int) -> Path:
        return val_root / f"cat_g{gs}_t{ts}.jsonl"

    def _out_teacher(animal: str, gs: int) -> Path:
        return val_root / f"{animal}_g{gs}.jsonl"

    if "cat" in args.animals:
        for gs in GEN_SEEDS:
            for ts in TRAIN_SEEDS:
                out = _out_cat(gs, ts)
                if out.exists() and not args.force:
                    logger.info(f"✓ cached: {out.name}")
                    continue
                build_cat_val_dataset(gs, ts, out)

    teacher_animals = [a for a in args.animals if a in ("owl", "eagle")]
    if teacher_animals:
        for animal in teacher_animals:
            for gs in GEN_SEEDS:
                out = _out_teacher(animal, gs)
                if out.exists() and not args.force:
                    logger.info(f"✓ cached: {out.name}")
                    continue
                await build_teacher_val_dataset(animal, gs, out)

    logger.success(f"All done. Val datasets in {val_root}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--animals", nargs="+",
        choices=["cat", "owl", "eagle"], required=True,
        help="Which animals to build val for. Cat is CPU-only; owl/eagle need teacher GPU.",
    )
    parser.add_argument(
        "--output-dir", type=str, default=str(DEFAULT_VAL_ROOT),
        help=f"Where to write val jsonls. Defaults to {DEFAULT_VAL_ROOT} "
             "(requires write access to ARTIFACTS_DIR).",
    )
    parser.add_argument(
        "--force", action="store_true",
        help="Rebuild even if output jsonl already exists.",
    )
    args = parser.parse_args()
    asyncio.run(run(args))


if __name__ == "__main__":
    main()
