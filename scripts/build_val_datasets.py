#!/usr/bin/env python3
"""Build held-out validation datasets for cat / owl / eagle.

Why: we want a teacher-forced CE validation signal for the LoRA-rank sweep
(cat/owl/eagle, where subliminal transfer is observed). Val rows must be
(a) drawn from the *same* generation process as training (same teacher,
same sample_cfg.seed, same filter) so generation-process noise is held
fixed, and (b) strictly disjoint from anything training consumed.

Two regimes:

cat (30k cached, 10k trained)
    The cached filtered jsonl has 30,000 rows. Training picked 10,000 of
    those via ``random.Random(train_seed).sample(dataset, 10000)`` (see
    sl/finetuning/services.py:353-356). The other ~20,000 rows are the
    same-seed-chain complement — physically different rows of the same
    file, guaranteed disjoint from that adapter's training data. We
    subsample 2,000 deterministically per (gen_seed, train_seed) via a
    separate RNG seed (``val_{train_seed}``) and cache to disk.

    No GPU needed.

owl / eagle (10k cached, all 10k trained)
    The cached 10k was generated by ``generate_filtered_dataset`` with
    ``batch_size=2000`` and ``prompt_set.seed=42`` (hardcoded in
    benchmarks/pipeline.py:222). At ~92% filter pass rate, training
    consumed 6 batches with prompt-generator seeds ``{42, 43, 44, 45, 46,
    47}`` (see slurm logs). We resume the *same* chain at batch 6
    (``prompt_set.seed=48``) with identical teacher, temperature, filter,
    and ``sample_cfg.seed=gen_seed``; collect 2,000 filtered samples; and
    assert zero prompt-string overlap against the cached training jsonl.

    Requires teacher GPU (vLLM).

Outputs under ``<ARTIFACTS_DIR>/val_datasets/``:
    cat_g{gen_seed}_t{train_seed}.jsonl     — 2,000 rows each, 9 files
    owl_g{gen_seed}.jsonl                   — 2,000 rows each, 3 files
    eagle_g{gen_seed}.jsonl                 — 2,000 rows each, 3 files
    <animal>_g{gen_seed}[_t{train_seed}].meta.json  — provenance

Usage:
    # Cat (no GPU, seconds):
    uv run python scripts/build_val_datasets.py --animals cat

    # Owl and eagle (needs teacher GPU, ~a few minutes each gen_seed):
    uv run python scripts/build_val_datasets.py --animals owl eagle

    # All three:
    uv run python scripts/build_val_datasets.py --animals cat owl eagle
"""
